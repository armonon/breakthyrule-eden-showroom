#!/usr/bin/env node
// Builds labkit/artwork-pool.mjs: the graphics the Lab's picker and the Altar of Chance can use.
//   id          stable file id (sorted, so a stored seed keeps mapping to the same graphic)
//   name        the original file name (kept for the studio)
//   display     a tidied name for customers (casing fixed, file noise removed)
//   tags        picker categories, by keyword
//   explicit    hidden in the picker unless the customer turns on "Show explicit graphics"
//   collection  the graphic shares its name with a garment in the collection ("From the collection" row)
// Re-run after importing new graphics (npm run graphics:add does it for you).
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const load = file => { const box = { window: {} }; vm.runInNewContext(fs.readFileSync(path.join(ROOT, file), 'utf8'), box); return box.window; };
const graphics = load('breakthyrule-assets.js').breakthyruleAssets.graphics || [];
const collection = (load('garment-catalog.js').showroomCollection || []).map(g => g.name);

const readable = n => n.length <= 24 && /[a-z]{2}/i.test(n) && !/\d{3,}|^img\b|chatgpt|gemini|copy|[a-z0-9]{12,}/i.test(n);
const SMALL = new Set(['a', 'an', 'and', 'of', 'the', 'to', 'in', 'on', 'for', 'is', 'with', 'by', 'or', 'at', 'as']);
function display(name) {
  let n = name.replace(/\(.*?\)/g, ' ').replace(/[_]+/g, ' ').replace(/\s+\d+$/, '').replace(/(?<=[a-z])\d+$/i, '').replace(/\s+/g, ' ').trim();
  if (!n) n = name;
  return n.split(' ').map((w, i) => {
    if (/^[A-Z0-9&!?.,'-]{2,4}$/.test(w)) return w; // keep short acronyms like DTF, GOD, 007
    const lw = w.toLowerCase();
    if (i > 0 && SMALL.has(lw)) return lw;
    return lw.charAt(0).toUpperCase() + lw.slice(1);
  }).join(' ');
}
const TAGS = [
  ['Faith', /angel|god|jesus|christ|cross|holy|faith|divine|heaven|saint|pray|church|bible|halo|chrism|devot|compassion|mother|seed|avalon|sacred|spirit|soul|nun|cupid/i],
  ['Eyes', /eye|see|vision|watch|look/i],
  ['Love & desire', /love|desire|kiss|heart|carnal|lust|lover|sexy|romance|valentine|barbie|girls?/i],
  ['Chaos', /anarch|destroy|chaos|war|demoli|evil|devil|baphomet|spell|cult|crazy|angry|burn|cremation|bomb|gun|dead|death|vampire/i],
  ['Nature', /flower|bee|bird|dove|horse|fruit|apple|rose|garden|tree|centaur|alien|planet|star|moon|sun|grape|animal/i],
  ['Mind', /mind|dream|think|feel|create|creat|explore|beyond|connect|energy|vibe|contact|high|evidence|talent/i]
];
const EXPLICIT = /fuck|shit|bitch|masturb|\bdtf\b|porn|nude|cock|pussy|dick|boobie/i;
const norm = s => s.toLowerCase().replace(/[^a-z0-9 ]+/g, ' ').replace(/\b(tee|tank|hoodie|crewneck|longsleeve|thermal|crop|beanie|gloves|jacket|sleeve|3 4)\b/g, ' ').replace(/\s+/g, ' ').trim();
const collectionNames = collection.map(norm).filter(n => n.length >= 3);

const pool = graphics.filter(g => readable(g.name)).map(g => {
  const tags = TAGS.filter(([, re]) => re.test(g.name)).map(([t]) => t);
  const key = norm(g.name);
  const entry = { id: g.id, name: g.name, display: display(g.name), tags: tags.length ? tags : ['Words'] };
  if (EXPLICIT.test(g.name)) entry.explicit = true;
  const whole = new RegExp('(^| )' + key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '( |$)');
  if (key.length >= 3 && collectionNames.some(c => c === key || (key.length >= 5 && whole.test(c)))) entry.collection = true;
  return entry;
}).sort((a, b) => a.id.localeCompare(b.id));
// Two files that tidy to the same name: the later ones get "(alt)", "(alt 2)"…
const seenNames = new Map();
for (const p of pool) { const k = p.display.toLowerCase(), n = seenNames.get(k) || 0; if (n) p.display += n === 1 ? ' (alt)' : ` (alt ${n})`; seenNames.set(k, n + 1); }

const out = path.join(ROOT, 'labkit/artwork-pool.mjs');
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
const ids = JSON.stringify(pool.map(p => p.id));
const prevVersion = Number(/POOL_VERSION = (\d+)/.exec(prev)?.[1] || 0);
const prevIds = /POOL_IDS = (\[.*?\]);/.exec(prev)?.[1] ?? JSON.stringify(JSON.parse(/ARTWORK_POOL = (\[.*?\]);/.exec(prev)?.[1] || '[]').map(p => p.id));
const version = prevIds === ids ? (prevVersion || 1) : prevVersion + 1; // bumps only when the set of graphics changes
fs.writeFileSync(out, `// Generated by tools/lab/build-artwork-pool.mjs — do not edit by hand.
export const POOL_VERSION = ${version};
export const POOL_IDS = ${ids};
export const ARTWORK_POOL = ${JSON.stringify(pool)};
export const artworkThumb = id => '/images/breakthyrule/graphics/thumb/' + id + '.webp';
export const PICKER_TAGS = ${JSON.stringify(['From the collection', ...TAGS.map(([t]) => t), 'Words'])};
`);
console.log('labkit/artwork-pool.mjs:', pool.length, 'graphics,', pool.filter(p => p.explicit).length, 'explicit,', pool.filter(p => p.collection).length, 'from the collection, version', version);
