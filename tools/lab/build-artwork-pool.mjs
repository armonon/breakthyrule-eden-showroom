#!/usr/bin/env node
// Builds labkit/artwork-pool.mjs: the curated Break Thy Rule graphics the Altar of Chance may reference.
// Sorted and stable, so a stored seed always maps to the same artwork. Re-run after importing new graphics;
// existing seeds keep their meaning only if the list is unchanged, so the version number goes up on change.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const box = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'breakthyrule-assets.js'), 'utf8'), box);
const readable = n => n.length <= 24 && /[a-z]{2}/i.test(n) && !/\d{3,}|^img\b|chatgpt|gemini|copy|[a-z0-9]{12,}/i.test(n);
const pool = (box.window.breakthyruleAssets.graphics || []).filter(g => readable(g.name)).map(g => ({ id: g.id, name: g.name })).sort((a, b) => a.id.localeCompare(b.id));
const out = path.join(ROOT, 'labkit/artwork-pool.mjs');
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
const body = JSON.stringify(pool);
const prevVersion = Number(/POOL_VERSION = (\d+)/.exec(prev)?.[1] || 0);
const version = prev.includes(body) ? prevVersion || 1 : prevVersion + 1;
fs.writeFileSync(out, `// Generated by tools/lab/build-artwork-pool.mjs — do not edit by hand.\nexport const POOL_VERSION = ${version};\nexport const ARTWORK_POOL = ${body};\nexport const artworkThumb = id => '/images/breakthyrule/graphics/thumb/' + id + '.webp';\n`);
console.log('labkit/artwork-pool.mjs:', pool.length, 'graphics, version', version);
