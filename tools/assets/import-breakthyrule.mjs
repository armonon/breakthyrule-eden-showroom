#!/usr/bin/env node
// Imports the Break Thy Rule source folder (GRAPHICS, favs gallery, ADVERTS) into
// web-sized WebP files plus a manifest the cover and gallery read at runtime.
// Usage: node tools/assets/import-breakthyrule.mjs [source-folder] [--redo favs,graphics,adverts]
//   --redo re-encodes (overwrites) the listed sets instead of skipping files that already exist.
// Needs macOS (swiftc, sips) and `cwebp` (brew install webp). Phone photos are turned upright from
// their EXIF orientation by tools/assets/oriented-resize.swift, compiled on first run.
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdir, readdir, rm, writeFile, mkdtemp, stat } from 'node:fs/promises';
import { tmpdir, cpus } from 'node:os';
import path from 'node:path';

const run = promisify(execFile);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const argv = process.argv.slice(2);
const redoAt = argv.indexOf('--redo');
const redo = new Set(redoAt >= 0 ? (argv.splice(redoAt, 2)[1] || '').split(',') : []);
const source = path.resolve(argv[0] || path.join(process.env.HOME, 'Downloads/breakthyrule'));
const outRoot = path.join(root, 'images/breakthyrule');
const IMAGE = /\.(png|jpe?g|heic)$/i;

const sets = [
  { key: 'graphics', dir: 'GRAPHICS', thumb: 360, full: 1400, quality: 82 },
  { key: 'favs', dir: 'favs gallery', thumb: 640, full: 1800, quality: 80 },
  { key: 'adverts', dir: 'ADVERTS', thumb: 320, full: 2100, quality: 84 }
];

const slug = name => name.replace(/\.[^.]+$/, '').normalize('NFKD').replace(/[^\w\s-]/g, '').trim()
  .replace(/[\s_]+/g, '-').replace(/-+/g, '-').toLowerCase() || 'image';
const title = name => name.replace(/\.[^.]+$/, '').replace(/\s*\(\d+\)$/, '').replace(/\s+copy$/i, '')
  .replace(/[_-]+/g, ' ').replace(/\s+/g, ' ').trim();

async function size(file) {
  const { stdout } = await run('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file]);
  const w = +stdout.match(/pixelWidth: (\d+)/)[1], h = +stdout.match(/pixelHeight: (\d+)/)[1];
  return { w, h };
}

let resizer;
async function encode(input, output, max, quality, scratch) {
  const png = path.join(scratch, path.basename(output) + '.png');
  await run(resizer, [input, String(max), png]);
  await run('cwebp', ['-quiet', '-q', String(quality), '-alpha_q', '90', '-m', '5', png, '-o', output]);
  await rm(png, { force: true });
}

async function pool(items, limit, fn) {
  let next = 0;
  await Promise.all(Array.from({ length: limit }, async () => {
    while (next < items.length) { const i = next++; await fn(items[i], i); }
  }));
}

const scratch = await mkdtemp(path.join(tmpdir(), 'btr-import-'));
resizer = path.join(scratch, 'oriented-resize');
await run('swiftc', ['-O', path.join(root, 'tools/assets/oriented-resize.swift'), '-o', resizer]);
const manifest = {};
for (const set of sets) {
  const dir = path.join(source, set.dir);
  const files = (await readdir(dir)).filter(f => IMAGE.test(f) && !f.startsWith('.')).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
  await mkdir(path.join(outRoot, set.key, 'thumb'), { recursive: true });
  await mkdir(path.join(outRoot, set.key, 'full'), { recursive: true });
  const used = new Set(), entries = [];
  await pool(files, Math.max(2, cpus().length - 1), async (file, index) => {
    let id = slug(file); while (used.has(id)) id += '-b'; used.add(id);
    const input = path.join(dir, file);
    try {
      const thumb = `${set.key}/thumb/${id}.webp`, full = `${set.key}/full/${id}.webp`;
      const thumbOut = path.join(outRoot, thumb), fullOut = path.join(outRoot, full);
      const fresh = redo.has(set.key);
      if (fresh || !(await stat(thumbOut).catch(() => null))) await encode(input, thumbOut, set.thumb, set.quality, scratch);
      if (fresh || !(await stat(fullOut).catch(() => null))) await encode(input, fullOut, set.full, set.quality, scratch);
      const dims = await size(fullOut);
      const ratio = dims.h / dims.w;
      entries[index] = { id, name: title(file), ratio: +ratio.toFixed(4), thumb: '/images/breakthyrule/' + thumb, full: '/images/breakthyrule/' + full };
      process.stdout.write('.');
    } catch (error) {
      console.warn(`\nskipped ${set.dir}/${file}: ${error.message.split('\n')[0]}`);
    }
  });
  manifest[set.key] = entries.filter(Boolean);
  console.log(`\n${set.key}: ${manifest[set.key].length} images`);
}
await rm(scratch, { recursive: true, force: true });

const banner = '// Generated by tools/assets/import-breakthyrule.mjs. Do not edit by hand.\n';
await writeFile(path.join(root, 'breakthyrule-assets.js'),
  banner + "'use strict';\nwindow.breakthyruleAssets=" + JSON.stringify(manifest) + ';\n');
console.log('wrote breakthyrule-assets.js');
