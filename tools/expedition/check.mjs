import {readdirSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url));
const files=readdirSync(new URL('./',import.meta.url)).filter(name=>name.endsWith('-test.mjs')).map(name=>'tools/expedition/'+name);
files.push('tools/motion/natural-motion-test.mjs','tools/motion/visitor-smoothing-test.mjs','tools/story/horror-interaction-test.mjs','tools/movement/player-bail-test.mjs','tools/movement/dive-lifecycle-test.mjs','tools/movement/mobile-controls-test.mjs','server/expedition.test.mjs','server/expedition-http.test.mjs','server/expedition-storage.test.mjs','server/world.test.mjs');
const soak=process.argv.includes('--soak');
const concurrency=process.env.EDEN_TEST_CONCURRENCY||'2';
if(!/^[1-9]\d*$/.test(concurrency))throw new Error('EDEN_TEST_CONCURRENCY must be a positive integer');
console.log(soak?'Includes accelerated simulation soak, not browser endurance.':'Excludes accelerated 30-minute simulation soak; use --soak to include it.');
console.log('Test workers:',concurrency);
const result=spawnSync(process.execPath,['--test','--test-concurrency='+concurrency,...(!soak?['--test-skip-pattern=accelerated thirty-minute']:[]),...files],{cwd:root,stdio:'inherit'});
if(result.error)console.error(result.error);
if(result.signal)console.error('Test process interrupted:',result.signal);
process.exitCode=typeof result.status==='number'?result.status:1;
